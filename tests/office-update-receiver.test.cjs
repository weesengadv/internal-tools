const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { Readable } = require('node:stream');
const { createUpdateReceiver } = require('../src/deployment/update-receiver.cjs');
const { requestReceiver } = require('../src/deployment/pinned-client.cjs');
const { signRelease } = require('../src/deployment/update-signing.cjs');
test('pinned TLS receiver authenticates, verifies signatures and archive bytes before applying', async t => {
  const folder = fs.mkdtempSync(path.join(__dirname,'../output/receiver-qa-'));
  execFileSync('C:/Program Files/Git/usr/bin/openssl.exe', ['req','-x509','-newkey','rsa:2048','-nodes','-keyout',path.join(folder,'key.pem'),'-out',path.join(folder,'cert.pem'),'-days','1','-subj','/CN=localhost'], {stdio:'ignore'});
  const cert = fs.readFileSync(path.join(folder,'cert.pem')); const key = fs.readFileSync(path.join(folder,'key.pem'));
  const keys = crypto.generateKeyPairSync('ed25519'); const token = crypto.randomBytes(32).toString('base64');
  let applied = 0; let requests = 0; let releaseApply;
  const server = createUpdateReceiver({directory:folder,installDir:folder,subnet:'192.168.0.0/24',publicKey:keys.publicKey.export({type:'spki',format:'pem'}),token}, {tls:{cert,key},applyUpdate:async(job,archive,save)=>{applied++;assert.equal(fs.readFileSync(archive,'utf8'),'zip fixture');await new Promise(resolve=>{releaseApply=resolve});save({status:'succeeded'});}});
  server.on('request',()=>requests++);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const pairing = {target:`https://127.0.0.1:${server.address().port}`,token,certificateSha256:crypto.createHash('sha256').update(new crypto.X509Certificate(cert).raw).digest('hex')};
  await assert.rejects(requestReceiver({...pairing,certificateSha256:'0'.repeat(64)},'/v1/status'),/certificate changed/);
  assert.equal(requests,0,'Wrong certificate must receive no HTTP credentials or body');
  await assert.rejects(requestReceiver({...pairing,token:'bad'},'/v1/status'),/authentication/);
  const bytes = Buffer.from('zip fixture'); const metadata = {release:'office-test1',sha256:crypto.createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length};
  const upload = (envelope,body=bytes) => requestReceiver(pairing,'/v1/releases',{method:'POST',headers:{'content-type':'application/zip','content-length':body.length,'x-weeseng-staff-saved':'yes','x-weeseng-release':Buffer.from(JSON.stringify(envelope)).toString('base64url')},stream:Readable.from([body])});
  const wrongKeys = crypto.generateKeyPairSync('ed25519');
  await assert.rejects(upload(signRelease(metadata,wrongKeys.privateKey)),/signature/);
  await assert.rejects(upload(signRelease({...metadata,sha256:'0'.repeat(64)},keys.privateKey)),/verification/);
  assert.equal(applied,0);
  const response = await upload(signRelease(metadata,keys.privateKey));assert.equal(response.job.status,'verified');
  await new Promise(resolve=>setImmediate(resolve));assert.equal(applied,1);
  await assert.rejects(upload(signRelease(metadata,keys.privateKey)),/already in progress/);
  releaseApply();await new Promise(resolve=>setImmediate(resolve));
  assert.equal((await requestReceiver(pairing,'/v1/status')).job.status,'succeeded');
});
